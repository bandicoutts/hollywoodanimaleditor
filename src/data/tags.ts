export const ALL_KNOWN_TAGS = new Set<string>(
  TAG_GROUPS.flatMap((g) => g.tags)
);

export function getTagGroup(tagId: string): TagGroup | undefined {
  return TAG_GROUPS.find((g) => g.tags.includes(tagId));
}

export function formatTagLabel(tagId: string): string {
  return tagId
    .replace(/^[A-Z]+_/, "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}
